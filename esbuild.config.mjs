import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/**
 * Sourcemaps only when asked for: `node esbuild.config.mjs --sourcemap`.
 *
 * They used to be on for every dev build, and they are the reason the plugin
 * stopped loading on a phone. `outdir` is the plugin folder — it has to be, or
 * the installed plugin is stale — so the file the watcher writes is the file
 * Obsidian loads and the file that gets synced to every other device. An inline
 * map turns 460KB of bundle into 5.4MB of base64, and a phone asked to parse and
 * evaluate that has to hold the whole thing in memory at once. Desktop shrugged;
 * mobile did not, and it looked like a code problem because every build after the
 * codebase grew past a certain size failed the same way.
 *
 * Dev builds are still unminified and still readable. What is gone is the four
 * and a half megabytes of it that only a desktop debugger was ever going to
 * read.
 */
const maps = process.argv.includes("--sourcemap");

/**
 * Optional second home for the build: `OBSIDIAN_PLUGIN_DIR`, from the
 * environment or a gitignored `.env`, pointing at
 * `<vault>/.obsidian/plugins/scout`. For clones that do not live inside a
 * vault. Unset, the repo root is the plugin folder and nothing is copied.
 */
// `loadEnvFile` needs Node 20.12+; older Node can still use a real env var.
if (fs.existsSync(".env")) process.loadEnvFile?.(".env");
const pluginDir = process.env.OBSIDIAN_PLUGIN_DIR
	? path.resolve(process.env.OBSIDIAN_PLUGIN_DIR)
	: null;
const copyTarget =
	pluginDir && pluginDir !== path.resolve(".") ? pluginDir : null;
const ARTIFACTS = ["main.js", "manifest.json", "styles.css"];

function copyToPlugin(file) {
	if (!copyTarget || !fs.existsSync(file)) return;
	fs.copyFileSync(file, path.join(copyTarget, file));
}

/** Copies the bundle after every build, and asks hot-reload to watch it. */
const copyPlugin = {
	name: "copy-to-plugin-dir",
	setup(build) {
		build.onEnd((result) => {
			if (!copyTarget || result.errors.length > 0) return;
			fs.mkdirSync(copyTarget, { recursive: true });
			const marker = path.join(copyTarget, ".hotreload");
			if (!fs.existsSync(marker)) fs.writeFileSync(marker, "");
			for (const file of ARTIFACTS) copyToPlugin(file);
			console.log(`[scout] copied to ${copyTarget}`);
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	// styles.css is hand-written at the root and not bundled; Obsidian loads it
	// from the plugin folder directly.
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: !prod && maps ? "inline" : false,
	treeShaking: true,
	// Always build to the plugin root: Obsidian loads main.js from there, so a
	// production build that only wrote to dist/ left the installed plugin stale.
	outdir: ".",
	minify: prod,
	plugins: [copyPlugin],
	loader: {
		".ts": "ts",
		".tsx": "tsx",
		".css": "css",
	},
});

if (prod) {
	await context.rebuild();
	// Mirror the release artifacts into dist/ for uploading to GitHub.
	fs.mkdirSync("dist", { recursive: true });
	for (const file of ARTIFACTS) {
		if (fs.existsSync(file)) fs.copyFileSync(file, `dist/${file}`);
	}
	process.exit(0);
} else {
	await context.watch();
	// esbuild only sees main.js. hot-reload notices a styles.css edit in the
	// plugin folder itself, so these only need copying when that is elsewhere.
	if (copyTarget) {
		for (const file of ["styles.css", "manifest.json"]) {
			let pending = null;
			fs.watch(file, () => {
				clearTimeout(pending);
				pending = setTimeout(() => {
					copyToPlugin(file);
					console.log(`[scout] copied ${file}`);
				}, 50);
			});
		}
	}
}
