/**
 * The genres Scout knows, per family of media.
 *
 * Sources disagree about what a genre is. TMDB has "Sci-Fi & Fantasy" for
 * television and two separate genres for film; Open Library has "subjects",
 * which run from "Science fiction" to "nyt:paperback_books=2011-06-11";
 * MusicBrainz has folksonomy tags like "british" and "2010s". Writing those
 * down verbatim made the library's genre list hundreds long and mostly noise.
 *
 * So each family has one vocabulary: a short list of main genres, each with a
 * few sub-genres beneath it. Everything a source says is mapped onto it (see
 * `genres.ts`), and what does not map is left out of the genre property.
 *
 * Families are kept apart because the words do not travel: "Drama" on a film
 * is not "Drama" on a book (a play), and nobody browsing music wants "Thriller".
 * Where the same word does mean the same thing — "Fantasy", "Horror" — it is
 * the same label in each, so filtering on it reaches across them.
 *
 * Aliases are compared after normalising (lowercase, accents and punctuation
 * dropped, "&" read as "and", hyphens as spaces), so "Sci-Fi", "sci fi" and
 * "SciFi" need listing only once each where they differ by more than that.
 */

export type GenreDomain = "screen" | "books" | "games" | "music";

export interface GenreDef {
	label: string;
	/** The main genre this one sits under. Absent on main genres. */
	parent?: string;
	/** Other main genres this one also implies — a romantic comedy is both. */
	also?: string[];
	aliases?: string[];
	/**
	 * Only used when nothing more specific was found. "Fiction" on a novel is
	 * true and says nothing, but it beats having no genre at all.
	 */
	fallback?: boolean;
}

